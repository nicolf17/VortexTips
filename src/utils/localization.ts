export function getLocalizedTeamName(name: string): string {
  if (!name) return '';
  const cleaned = name.trim();
  const lower = cleaned.toLowerCase();
  
  if (TEAM_NAME_MAP[lower]) {
    return TEAM_NAME_MAP[lower];
  }

  const unaccented = lower.normalize('NFD').replace(/[\u0300-\u036f]/g, '');
  if (TEAM_NAME_MAP[unaccented]) {
    return TEAM_NAME_MAP[unaccented];
  }

  return cleaned;
}

export function translateTeamName(name?: string): string {
  if (!name) return '';
  return getLocalizedTeamName(name);
}

export function translateStatus(status?: string, timeDisplay?: string): string {
  if (!status) return timeDisplay || 'Previa';
  const s = status.toUpperCase();
  if (s === 'LIVE' || s === 'IN') return 'EN VIVO';
  if (s === 'FINISHED' || s === 'POST' || s === 'FT') return 'FINALIZADO';
  if (s === 'SCHEDULED' || s === 'PRE') return timeDisplay || 'PREVIA';
  if (s === 'POSTPONED') return 'APLAZADO';
  if (s === 'CANCELLED') return 'CANCELADO';
  if (s === 'SUSPENDED') return 'SUSPENDIDO';
  return timeDisplay || status;
}

